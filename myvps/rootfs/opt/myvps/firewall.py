"""Install container-only egress restrictions before starting any services."""
import ipaddress
import json
from pathlib import Path
import re
import subprocess


DEFAULTS = {'enabled': True, 'public_ipv4': '', 'blocked_ipv4_networks': []}
# Include special-use destinations, not just RFC1918. Loopback is allowed by
# interface below, rather than permitting packets to 127/8 on another interface.
BLOCKED_IPV4 = (
    '0.0.0.0/8', '10.0.0.0/8', '100.64.0.0/10', '127.0.0.0/8',
    '169.254.0.0/16', '172.16.0.0/12', '192.0.0.0/24', '192.0.2.0/24',
    '192.168.0.0/16', '198.18.0.0/15', '198.51.100.0/24',
    '203.0.113.0/24', '224.0.0.0/4', '240.0.0.0/4',
)
PUBLIC_IP_SERVICES = ('https://api.ipify.org', 'https://checkip.amazonaws.com')
DROP_CAPABILITIES = [
    '--bounding-set=-net_admin,-net_raw', '--inh-caps=-net_admin,-net_raw',
    '--ambient-caps=-net_admin,-net_raw',
]


def validate(source):
    if not isinstance(source, dict):
        raise ValueError('network_protection must be a configuration object')
    settings = {**DEFAULTS, **source}
    if type(settings['enabled']) is not bool:
        raise ValueError('network_protection.enabled must be true or false')
    if not isinstance(settings['public_ipv4'], str):
        raise ValueError('network_protection.public_ipv4 must be an address or an empty string')
    if settings['public_ipv4']:
        address = ipaddress.IPv4Address(settings['public_ipv4'])
        if not address.is_global or address.is_multicast:
            raise ValueError('network_protection.public_ipv4 must be a public IPv4 address')
        settings['public_ipv4'] = str(address)
    networks = settings['blocked_ipv4_networks']
    if not isinstance(networks, list) or any(not isinstance(item, str) for item in networks):
        raise ValueError('network_protection.blocked_ipv4_networks must be a list of IPv4 networks')
    settings['blocked_ipv4_networks'] = [str(ipaddress.IPv4Network(item, strict=False)) for item in networks]
    return settings


def dns_servers(path=Path('/etc/resolv.conf')):
    servers = []
    lines = path.read_text().splitlines()
    for line in lines:
        fields = line.split('#', 1)[0].split()
        if fields and fields[0] == 'nameserver' and len(fields) == 2:
            address = ipaddress.ip_address(fields[1])
            if getattr(address, 'scope_id', None):
                raise ValueError('Scoped DNS addresses are not supported by network protection')
            if address.is_unspecified or address.is_multicast:
                raise ValueError('Invalid DNS resolver address')
            servers.append(str(address))
    # Docker's embedded resolver can forward queries from this same network
    # namespace to its configured upstream (HA uses 172.30.32.3). Permit ONLY
    # DNS to those exact, root-owned Docker configuration addresses as well.
    if lines and lines[0] == '# Generated by Docker Engine.':
        for line in lines:
            if line.startswith('# ExtServers: [') and line.endswith(']'):
                for token in line[len('# ExtServers: ['):-1].split():
                    token = re.sub(r'^host\((.*)\)$', r'\1', token)
                    address = ipaddress.ip_address(token)
                    if getattr(address, 'scope_id', None) or address.is_unspecified or address.is_multicast:
                        raise ValueError('Invalid upstream DNS resolver address')
                    servers.append(str(address))
    if not servers:
        raise ValueError('Network protection could not identify a DNS resolver')
    return sorted(set(servers))


def ruleset(resolvers, blocked):
    # Do not flush Docker's DNS/NAT tables. Replace only our own table, atomically.
    rules = ['add table inet myvps', 'flush table inet myvps',
             'add set inet myvps blocked_ipv4 { type ipv4_addr; flags interval; auto-merge; }',
             'add element inet myvps blocked_ipv4 { ' + ', '.join(blocked) + ' }',
             'add chain inet myvps output { type filter hook output priority filter; policy drop; }',
             'add rule inet myvps output ct state invalid drop',
             'add rule inet myvps output ct state established,related accept',
             'add rule inet myvps output oifname "lo" accept']
    for server in resolvers:
        family = 'ip' if ipaddress.ip_address(server).version == 4 else 'ip6'
        for protocol in ('udp', 'tcp'):
            rules.append(f'add rule inet myvps output {family} daddr {server} {protocol} dport 53 accept')
    # Keep IPv6 neighbour discovery usable for replies to incoming IPv6 clients.
    # New application connections over IPv6 are denied, including globally routed
    # home IPv6 addresses, IPv4-mapped addresses, and local-link destinations.
    rules += [
        'add rule inet myvps output meta l4proto ipv6-icmp ip6 hoplimit 255 '
        'icmpv6 type { nd-neighbor-solicit, nd-neighbor-advert } accept',
        'add rule inet myvps output ip daddr @blocked_ipv4 counter reject with icmpx type admin-prohibited',
        'add rule inet myvps output meta nfproto ipv6 counter reject with icmpx type admin-prohibited',
        'add rule inet myvps output meta nfproto ipv4 accept',
    ]
    return '\n'.join(rules) + '\n'


def apply(resolvers, blocked):
    try:
        subprocess.run(['nft', '-f', '-'], input=ruleset(resolvers, blocked),
                       text=True, capture_output=True, check=True, timeout=15)
    except (OSError, subprocess.SubprocessError) as error:
        details = getattr(error, 'stderr', '') or str(error)
        raise ValueError('Network protection could not install its firewall; refusing to start. '
                         'The container needs NET_ADMIN at startup. ' + details.strip()) from error


def public_ipv4(settings):
    if settings['public_ipv4']:
        return settings['public_ipv4']
    for url in PUBLIC_IP_SERVICES:
        try:
            reply = subprocess.run([
                'curl', '-4', '--noproxy', '*', '--proto', '=https',
                '--fail', '--silent', '--show-error', '--connect-timeout', '5',
                '--max-time', '10', url,
            ], check=True, capture_output=True, text=True, timeout=12)
            address = ipaddress.IPv4Address(reply.stdout.strip())
            if address.is_global and not address.is_multicast:
                return str(address)
        except (OSError, ValueError, subprocess.SubprocessError):
            continue
    raise ValueError('Network protection could not determine the public IPv4 address; refusing to start. '
                     'Check internet/DNS access, or set network_protection.public_ipv4 in HA.')


def hostname_ipv4(hostnames):
    result = set()
    for hostname in hostnames:
        try:
            reply = subprocess.run(['getent', 'ahostsv4', hostname], check=True,
                                   capture_output=True, text=True, timeout=8)
            for line in reply.stdout.splitlines():
                address = ipaddress.IPv4Address(line.split()[0])
                if address.is_global and not address.is_multicast:
                    result.add(str(address))
        except (OSError, ValueError, subprocess.SubprocessError):
            # A domain might not be live yet. Our public-IP check is mandatory
            # and still prevents the usual router hairpin path in this case.
            continue
    return sorted(result)


def install(settings, hostnames, run_directory):
    settings = validate(settings)
    state = {'enabled': settings['enabled']}
    if settings['enabled']:
        resolvers = dns_servers()
        blocked = list(BLOCKED_IPV4) + settings['blocked_ipv4_networks']
        # Apply LAN restrictions before performing discovery or running package
        # installers. No web/SSH/service process exists during this bootstrap.
        apply(resolvers, blocked)
        address = public_ipv4(settings)
        addresses = sorted({address, *hostname_ipv4(hostnames)})
        blocked += [str(ipaddress.IPv4Network(address)) for address in addresses]
        apply(resolvers, blocked)
        state.update(dns_servers=resolvers, blocked_ipv4_networks=blocked,
                     public_ipv4=address, new_outbound_ipv6='blocked',
                     runtime_network_capabilities='removed')
    run_directory.mkdir(parents=True, exist_ok=True)
    (run_directory / 'firewall.json').write_text(json.dumps(state, indent=2) + '\n')
    return state
