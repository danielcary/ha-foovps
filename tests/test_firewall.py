"""Validate security-sensitive startup ordering and firewall configuration."""
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

sys.path.insert(0, '/opt/myvps')
import firewall


class FirewallTests(unittest.TestCase):
    def test_defaults_protect_existing_installations(self):
        self.assertEqual(firewall.validate({}), {
            'enabled': True, 'public_ipv4': '', 'blocked_ipv4_networks': []})

    def test_rejects_invalid_options_and_rule_injection(self):
        for settings in (
            [], {'enabled': 'true'}, {'public_ipv4': '192.168.1.1'},
            {'public_ipv4': '224.0.0.1'}, {'public_ipv4': '1.2.3.4; flush ruleset'},
            {'blocked_ipv4_networks': '10.0.0.0/8'},
            {'blocked_ipv4_networks': ['::/0']},
            {'blocked_ipv4_networks': ['10.0.0.0/8; accept']},
        ):
            with self.subTest(settings=settings), self.assertRaises((ValueError, TypeError)):
                firewall.validate(settings)

    def test_reads_only_explicit_dns_resolvers(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'resolv.conf'
            path.write_text('nameserver 127.0.0.11\nnameserver fd00::3 # resolver\nsearch local\n')
            self.assertEqual(firewall.dns_servers(path), ['127.0.0.11', 'fd00::3'])
            path.write_text('search local\n')
            with self.assertRaises(ValueError):
                firewall.dns_servers(path)

    def test_manual_public_address_does_not_contact_discovery_services(self):
        settings = firewall.validate({'public_ipv4': '1.1.1.1'})
        with patch.object(firewall.subprocess, 'run') as run:
            self.assertEqual(firewall.public_ipv4(settings), '1.1.1.1')
        run.assert_not_called()

    def test_docker_upstream_gets_only_a_dns_exception(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'resolv.conf'
            path.write_text('# Generated by Docker Engine.\nnameserver 127.0.0.11\n'
                            '# ExtServers: [172.30.32.3 host(192.168.65.7)]\n')
            self.assertEqual(firewall.dns_servers(path), ['127.0.0.11', '172.30.32.3', '192.168.65.7'])

    def test_discovery_rejects_private_results_and_uses_fallback(self):
        with patch.object(firewall.subprocess, 'run', side_effect=[
            subprocess.CompletedProcess([], 0, stdout='192.168.1.1\n'),
            subprocess.CompletedProcess([], 0, stdout='1.1.1.1\n'),
        ]):
            self.assertEqual(firewall.public_ipv4(firewall.DEFAULTS), '1.1.1.1')

    def test_discovery_failure_stops_startup(self):
        with patch.object(firewall.subprocess, 'run', side_effect=subprocess.TimeoutExpired('curl', 12)):
            with self.assertRaisesRegex(ValueError, 'refusing to start'):
                firewall.public_ipv4(firewall.DEFAULTS)

    def test_firewall_failure_prevents_discovery_and_success_status(self):
        with tempfile.TemporaryDirectory() as directory, \
                patch.object(firewall, 'dns_servers', return_value=['127.0.0.11']), \
                patch.object(firewall.subprocess, 'run', side_effect=OSError('not permitted')), \
                patch.object(firewall, 'public_ipv4') as discover:
            with self.assertRaisesRegex(ValueError, 'refusing to start'):
                firewall.install({}, [], Path(directory))
            discover.assert_not_called()
            self.assertFalse((Path(directory) / 'firewall.json').exists())

    def test_installs_baseline_before_discovery_and_blocks_home_public_addresses(self):
        events = []
        def apply(resolvers, blocked):
            events.append(('rules', list(blocked)))
        def public(settings):
            events.append(('discovery', None))
            return '1.1.1.1'
        with tempfile.TemporaryDirectory() as directory, \
                patch.object(firewall, 'dns_servers', return_value=['127.0.0.11']), \
                patch.object(firewall, 'apply', side_effect=apply), \
                patch.object(firewall, 'public_ipv4', side_effect=public), \
                patch.object(firewall, 'hostname_ipv4', return_value=['8.8.8.8']):
            firewall.install({}, ['example.com'], Path(directory))
            state = json.loads((Path(directory) / 'firewall.json').read_text())
        self.assertEqual([event[0] for event in events], ['rules', 'discovery', 'rules'])
        self.assertIn('10.0.0.0/8', events[0][1])
        self.assertIn('1.1.1.1/32', events[-1][1])
        self.assertIn('8.8.8.8/32', events[-1][1])
        self.assertEqual(state['new_outbound_ipv6'], 'blocked')

    def test_explicit_disable_is_recorded_without_changing_network(self):
        with tempfile.TemporaryDirectory() as directory, patch.object(firewall, 'apply') as apply:
            self.assertEqual(firewall.install({'enabled': False}, [], Path(directory)), {'enabled': False})
        apply.assert_not_called()


if __name__ == '__main__':
    unittest.main(verbosity=2)
